#!/usr/bin/env python3
"""
Last step of the pipeline: assembles the FINAL datasets into the structure
datasets/{chat,agentic,supporting}/ from the pipeline outputs (pipeline/out_*), which
already use English file names, column names and values. Files are cloned/copied, never
modified (conversations.jsonl gets message and token counts added, see docs/DATASETS.md); the intermediate files are not touched.

Publishes what exists and reports what is missing (e.g. adoption requires
--track-snippets / --adoption, classification is a separate paid step).
If only the annotated files are missing but the prerequisites are there, it runs the
exporters (export_*.py) that produce them.

It never overwrites: a destination file that is already present is skipped.

Usage:
  python pipeline/7_02_publish_datasets.py --out-dir release
  python pipeline/7_02_publish_datasets.py --out-dir release --chat-dir pipeline/out
"""
import argparse
import glob
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

LANGS = ["python", "javascript", "typescript", "java"]
ADOPTION_AGENTIC = ["adoption_cli_agent_direct", "adoption_cli_agent_fallback", "adoption_cli_agent_authorship",
                    "adoption_ide_direct", "adoption_ide_commit_message", "adoption_ide_fallback",
                    "adoption_whole_repo"]
ADOPTION_CHAT = ["snippet_timeline", "snippet_provenance", "snippet_provenance_corrected", "snippet_similarity",
                 "snippet_pr_commits", "snippet_codefile_commits", "snippet_codefile_commits_corrected"]


def copy_file(src, dst):
    """Clone (APFS) or copy src to dst without overwriting."""
    if sys.platform == "darwin":
        subprocess.run(["cp", "-cn", src, dst], check=False, stderr=subprocess.DEVNULL)
    if not os.path.exists(dst):
        shutil.copyfile(src, dst)


def copy_csv_renaming(src, dst, rename):
    """Copy a CSV renaming some header columns; the rest of the file is copied byte for byte."""
    import csv
    import io
    with open(src, "rb") as f:
        head = f.readline()
        cols = next(csv.reader([head.decode("utf-8")]))
        eol = "\r\n" if head.endswith(b"\r\n") else "\n"
        buf = io.StringIO()
        csv.writer(buf, lineterminator=eol).writerow([rename.get(c, c) for c in cols])
        with open(dst, "xb") as out:
            out.write(buf.getvalue().encode("utf-8"))
            shutil.copyfileobj(f, out, 16 * 1024 * 1024)


def filter_english(src, dst):
    """Copy a CSV keeping only the rows with prompt_is_english = yes (same columns, same order)."""
    import csv
    csv.field_size_limit(50_000_000)
    with open(src, "rb") as f:
        eol = "\r\n" if f.readline().endswith(b"\r\n") else "\n"
    with open(src, encoding="utf-8", newline="") as fin, open(dst, "x", encoding="utf-8", newline="") as fout:
        reader = csv.reader(fin)
        writer = csv.writer(fout, lineterminator=eol)
        header = next(reader)
        writer.writerow(header)
        i = header.index("prompt_is_english")
        for row in reader:
            if row[i] == "yes":
                writer.writerow(row)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out-dir", required=True, help="destination folder (contains datasets/)")
    ap.add_argument("--chat-dir", default=os.path.join(HERE, "out_ago2026"))
    ap.add_argument("--agentic-dir", default=os.path.join(HERE, "out_vibe_coding"))
    ap.add_argument("--chat-intent-dir", default=os.path.join(HERE, "4_01_chat_intent_classification", "data"))
    ap.add_argument("--agentic-intent-dir", default=os.path.join(HERE, "4_02_agentic_intent_classification", "data"))
    ap.add_argument("--browser-dir", default=os.path.join(HERE, "browser_dataset_en"),
                    help="browsers generated by generate_html_browser_{chat,agentic}_*.py")
    ap.add_argument("--legacy-browser-dir", default=os.path.join(HERE, "browser_dataset"),
                    help="browser_harness.html and the legacy browsers (browser_<language>.html)")
    ap.add_argument("--no-exports", action="store_true", help="do not run the exporters of the annotated files")
    a = ap.parse_args()
    D = os.path.join(a.out_dir, "datasets")
    stats = {"written": 0, "existing": 0, "missing": []}

    def put(src, dst_rel, rename=None):
        """Copies src into datasets/<dst_rel>; never overwrites."""
        if not os.path.exists(src):
            stats["missing"].append(src)
            return
        dst = os.path.join(D, dst_rel)
        if os.path.exists(dst):
            stats["existing"] += 1
            return
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if rename:
            copy_csv_renaming(src, dst, rename)
        else:
            copy_file(src, dst)
        stats["written"] += 1

    def put_english_only(src, dst_rel):
        """English-prompt-only variant of an agentic CSV; never overwrites."""
        if not os.path.exists(src):
            stats["missing"].append(src)
            return
        dst = os.path.join(D, dst_rel)
        if os.path.exists(dst):
            stats["existing"] += 1
            return
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        filter_english(src, dst)
        stats["written"] += 1

    def put_conversations(src, dst_rel):
        """conversations.jsonl with message and token counts added (lib_html_viewer_common.enrich_conversations)."""
        if not os.path.exists(src):
            stats["missing"].append(src)
            return
        dst = os.path.join(D, dst_rel)
        if os.path.exists(dst):
            stats["existing"] += 1
            return
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        import lib_html_viewer_common as hv
        print(f"-- adding message/token counts to {dst_rel}")
        hv.enrich_conversations(src, dst)
        stats["written"] += 1

    def export(script, directory, out_file, prereq):
        """If out_file is missing and the prerequisites are there, runs the exporter."""
        if a.no_exports or os.path.exists(os.path.join(directory, out_file)):
            return
        if all(os.path.exists(p) for p in prereq):
            print(f"-- exporting {out_file} ({script})")
            subprocess.run([sys.executable, os.path.join(HERE, script), directory], check=False)

    C, G, CI, GI, B = a.chat_dir, a.agentic_dir, a.chat_intent_dir, a.agentic_intent_dir, a.browser_dir
    BL = a.legacy_browser_dir
    export("5_01_chat_export_annotated_dataset.py", C, "chat_annotated_dataset.csv",
            [os.path.join(C, "snippet.csv"), os.path.join(C, "snippet_timeline.csv"),
             os.path.join(CI, "classification_per_row_4lang.csv")])
    export("5_02_agentic_export_candidates_dataset.py", G, "agentic_candidates_dataset.csv",
            [os.path.join(G, "conversations.jsonl"), os.path.join(GI, "message_row_map.csv")])
    export("5_03_agentic_export_annotated_dataset.py", G, "agentic_annotated_dataset.csv",
            [os.path.join(G, "agentic_candidates_dataset.csv")])
    export("5_04_agentic_export_pairs_all_languages.py", G, "pairs_agentic_all_languages.csv",
            [os.path.join(G, "agentic_annotated_dataset.csv")])

    # ---- chat
    put_conversations(f"{C}/conversations.jsonl", "chat/conversations.jsonl")
    put(f"{C}/snippet.csv", "chat/snippets_all_languages.csv")
    put(f"{C}/chat_annotated_dataset.csv", "chat/annotated_4_languages.csv")
    for l in LANGS:
        put(f"{B}/browser_chat_annotated_{l}.html", f"chat/html/browser_chat_annotated_{l}.html")
    # ---- agentic
    put_conversations(f"{G}/conversations.jsonl", "agentic/conversations.jsonl")
    put(f"{G}/pairs_agentic_all_languages.csv", "agentic/pairs_all_languages.csv")
    put(f"{G}/agentic_annotated_dataset.csv", "agentic/annotated_4_languages.csv")
    for l in LANGS:
        put(f"{B}/browser_agentic_annotated_{l}.html", f"agentic/html/browser_agentic_annotated_{l}.html")
    put(f"{BL}/browser_harness.html", "agentic/html/browser_harness.html")
    for f in sorted(glob.glob(f"{B}/browser_agentic_other_languages_*.html")):
        put(f, f"agentic/html/other_languages/{os.path.basename(f)}")
    # English-prompt-only variants (prompt_is_english = yes); the chat dataset is English-filtered by construction
    put_english_only(f"{G}/agentic_annotated_dataset.csv", "agentic/annotated_4_languages_english_only.csv")
    put_english_only(f"{G}/pairs_agentic_all_languages.csv", "agentic/pairs_all_languages_english_only.csv")
    put(f"{G}/harness_config.csv", "agentic/harness/harness_config.csv")
    hf = f"{G}/harness_files"
    if os.path.isdir(hf):
        dst = os.path.join(D, "agentic", "harness", "harness_files")
        if not os.path.exists(dst):
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            subprocess.run(["cp", "-Rcn", hf, dst], check=False, stderr=subprocess.DEVNULL)
            if not os.path.exists(dst):
                shutil.copytree(hf, dst)
            stats["written"] += 1
        else:
            stats["existing"] += 1
    else:
        stats["missing"].append(hf)
    # ---- supporting
    for f in ADOPTION_CHAT:
        put(f"{C}/{f}.csv", f"supporting/chat/adoption/{f}.csv")
    for pat in ("classification_per_row_4lang.csv", "message_row_map.csv"):
        put(f"{CI}/{pat}", f"supporting/chat/classification/{pat}")
    for pat in ("crosstab_*.csv", "distribution_*.csv", "completion_summary*.csv"):
        for f in sorted(glob.glob(f"{CI}/{pat}")):
            put(f, f"supporting/chat/classification/{os.path.basename(f)}")
    for f in ADOPTION_AGENTIC + ["repo_analysis"]:
        put(f"{G}/{f}.csv", f"supporting/agentic/adoption/{f}.csv")
    put(f"{GI}/message_row_map.csv", "supporting/agentic/classification/message_candidate_map.csv",
        rename={"row_id": "candidate_key"})  # here the column contains "sha::candidate_index"
    for f in sorted(glob.glob(f"{G}/intent_adoption_*.csv")) + [f"{G}/classification_per_pair_agentic.csv"]:
        put(f, f"supporting/agentic/classification/{os.path.basename(f)}")
    put(f"{G}/agentic_candidates_dataset.csv", "supporting/agentic/candidates/agentic_candidates_dataset.csv")
    put_english_only(f"{G}/agentic_candidates_dataset.csv",
                     "supporting/agentic/candidates/agentic_candidates_dataset_english_only.csv")

    put(f"{G}/snippet.csv", "supporting/legacy/agentic_snippets_chat_style.csv")

    print(f"Published: {stats['written']} | already present (skipped): {stats['existing']} | "
          f"missing sources: {len(stats['missing'])}")
    for m in stats["missing"]:
        print("   missing:", m)


if __name__ == "__main__":
    main()
